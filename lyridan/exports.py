"""Additional exports: syllabized text, romanized (enhanced) LRC."""
from __future__ import annotations

from typing import List

from .model import Line


def _ts(t: float, angle: bool = False) -> str:
    t = max(0.0, t)
    m = int(t // 60)
    s = t - m * 60
    body = f"{m:02d}:{s:05.2f}"
    return f"<{body}>" if angle else f"[{body}]"


def syllabized_text(lines: List[Line], syl_sep: str = "-", word_sep: str = " ",
                    timestamps: bool = False) -> str:
    out = []
    for ln in lines:
        text = word_sep.join(w.prefix + syl_sep.join(s.text for s in w.syllables) + w.suffix
                             for w in ln.words)
        out.append((_ts(ln.start) if timestamps else "") + text)
    return "\n".join(out) + "\n"


def lrc(lines: List[Line], enhanced: bool = False, offset: float = 0.0) -> str:
    out = []
    for ln in lines:
        if not enhanced:
            out.append(_ts(ln.start + offset) + " ".join(w.prefix + w.text + w.suffix for w in ln.words))
            continue
        parts = []
        for w in ln.words:
            parts.append(_ts(w.start + offset, True) + w.prefix + w.text + w.suffix)
        out.append(_ts(ln.start + offset) + " ".join(parts) + " " + _ts(ln.end + offset, True))
    return "\n".join(out) + "\n"


# ---------------------------------------------------------------------------
def _ttml_time(t: float) -> str:
    t = max(0.0, t)
    m = int(t // 60)
    s = t - 60 * m
    return f"{m}:{s:06.3f}" if m else f"{s:.3f}"


def _esc(s: str) -> str:
    return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace('"', "&quot;")


def _spans(pieces) -> str:
    out = []
    for i, p in enumerate(pieces):
        if p.start is None:
            out.append(_esc(p.text))
        else:
            out.append(f'<span begin="{_ttml_time(p.start)}" end="{_ttml_time(p.end if p.end is not None else p.start)}">'
                       f'{_esc(p.text)}</span>')
        if not p.joined and i < len(pieces) - 1:
            out.append(" ")
    return "".join(out)


def ttml(lyrics, lang: str = "", generator: str = "Lyridan") -> str:
    """Apple-Music-style syllable TTML (body + optional Latin transliteration block)."""
    lines = [l for l in lyrics.lines if l.pieces]
    lang = lang or lyrics.language or "en"
    translit = ""
    if any(l.romaji for l in lines):
        texts = "".join(f'<text for="L{i + 1}">{_spans(l.romaji)}</text>' for i, l in enumerate(lines) if l.romaji)
        translit = (f'<transliterations><transliteration xml:lang="{lang}-Latn">{texts}</transliteration>'
                    f'</transliterations>')
    end = max((l.end or 0) for l in lines) if lines else 0
    body = []
    for i, l in enumerate(lines):
        inner = _spans(l.pieces)
        if l.background:
            inner = f'<span ttm:role="x-bg">{inner}</span>'
        body.append(f'<p begin="{_ttml_time(l.start or 0)}" end="{_ttml_time(l.end or l.start or 0)}" '
                    f'itunes:key="L{i + 1}" ttm:agent="{_esc(l.agent or "v1")}">{inner}</p>')
    return ('<tt xmlns="http://www.w3.org/ns/ttml" xmlns:itunes="http://music.apple.com/lyric-ttml-internal" '
            'xmlns:ttm="http://www.w3.org/ns/ttml#metadata" itunes:timing="Word" '
            f'xml:lang="{_esc(lang)}"><head><metadata><ttm:agent type="person" xml:id="v1"/>'
            f'<iTunesMetadata xmlns="http://music.apple.com/lyric-ttml-internal" leadingSilence="0.000">'
            f'{translit}</iTunesMetadata><ttm:desc>Generated by {_esc(generator)} (audio alignment, '
            f'experimental)</ttm:desc></metadata></head>'
            f'<body dur="{_ttml_time(end)}"><div begin="{_ttml_time(lines[0].start if lines else 0)}" '
            f'end="{_ttml_time(end)}">{"".join(body)}</div></body></tt>\n')
